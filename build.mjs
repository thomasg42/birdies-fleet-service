#!/usr/bin/env node
import { mkdirSync, rmSync, writeFileSync, readdirSync, readFileSync, copyFileSync, statSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { SITE, liveServices } from './site.config.mjs';
import { PAGES } from './src/pages.mjs';
import { makeCtx, renderPage } from './src/layout.mjs';

const here = dirname(fileURLToPath(import.meta.url));

// The ?v= on every asset URL carries a hash of the CSS and JS sources, so a deploy that
// changes styles or scripts can never leave visitors on a cached old copy. A hand-bumped
// assetVersion was forgotten twice (Bridger 2026-10-03, Birdies 2026-10-22).
const assetSrc = join(here, 'src/assets');
const assetHash = createHash('sha1');
for (const name of readdirSync(assetSrc).filter((n) => /\.(css|js)$/.test(n)).sort()) {
  // Normalize line endings so Windows, Mac and Cursor's cloud compute the same hash.
  assetHash.update(name).update(readFileSync(join(assetSrc, name), 'utf8').replace(/\r\n/g, '\n'));
}
SITE.assetVersion = `${SITE.assetVersion}-${assetHash.digest('hex').slice(0, 8)}`;
const dev = process.argv.includes('--dev');
const outArg = process.argv.indexOf('--out');
const OUT = resolve(outArg > -1 ? process.argv[outArg + 1] : join(here, dev ? 'dev-build' : 'docs'));
const docsPath = resolve(here, 'docs');
if (dev && OUT === docsPath) {
  console.error('Refusing to write docs/ from a dev build.');
  process.exit(1);
}

function copyDir(from, to, skip) {
  if (!existsSync(from)) return;
  mkdirSync(to, { recursive: true });
  for (const name of readdirSync(from)) {
    if (name.startsWith('.') || skip.has(name)) continue;
    const a = join(from, name);
    const b = join(to, name);
    if (statSync(a).isDirectory()) copyDir(a, b, skip);
    else copyFileSync(a, b);
  }
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
copyDir(join(here, 'src/assets'), join(OUT, 'assets'), new Set(dev ? [] : ['booking-mock.js']));

const { api, ...rules } = SITE.booking;
const browserConfig = {
  dev,
  api: dev ? '/api' : (api || ''),
  leadEndpoint: SITE.leadEndpoint || '',
  phoneE164: SITE.phone.e164,
  phoneDisplay: SITE.phone.display,
  name: SITE.shortName,
  rules,
  services: liveServices(SITE).map((s) => ({ id: s.id, name: s.name })),
  assetVersion: SITE.assetVersion,
};
writeFileSync(join(OUT, 'assets/config.js'), `/* Generated by build.mjs from site.config.mjs. */\nwindow.BIRDIES_CONFIG = ${JSON.stringify(browserConfig)};\n`);
if (dev) {
  writeFileSync(join(OUT, 'assets/dev-boot.js'), `import { install } from './booking-mock.js';\nwindow.BIRDIES_DEV_BOOT = install;\n`);
}

const sitemap = [];
for (const page of PAGES) {
  const ctx = makeCtx(SITE, page.linkSlug ?? page.slug, { depth: page.depth, dev });
  const html = renderPage(ctx, page);
  const rel = page.file || (page.slug ? `${page.slug}/index.html` : 'index.html');
  mkdirSync(dirname(join(OUT, rel)), { recursive: true });
  writeFileSync(join(OUT, rel), html);
  if (page.inSitemap !== false && !page.noindex) {
    const loc = page.slug ? ctx.abs(`${page.slug}/`) : ctx.abs('');
    sitemap.push(loc);
  }
}

const base = SITE.url.replace(/\/$/, '');
writeFileSync(join(OUT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemap.map((loc) => `  <url><loc>${loc}</loc><lastmod>${SITE.updated}</lastmod></url>`).join('\n')}
</urlset>
`);
writeFileSync(join(OUT, 'robots.txt'), SITE.launched
  ? `User-agent: *\nAllow: /\n\nSitemap: ${base}/sitemap.xml\n`
  : `User-agent: *\nDisallow: /\n`);
writeFileSync(join(OUT, '.nojekyll'), '');
console.log(`Built ${PAGES.length} pages into ${OUT} (${dev ? 'DEV' : 'production'}, ${SITE.launched ? 'launched' : 'not launched'}).`);
